double CIF_97::Ro_2 ( double T_K, double P_MPa )
  {
  SetXY_2( T_K, P_MPa );
  double Ro = P_MPa * 1e3 / ( RT * Pi * G_2p ( T_K, P_MPa ));
  return Ro;
  }

double CIF_97::U_2 ( double T_K, double P_MPa )
  {
  SetXY_2( T_K, P_MPa );
  double U = RT * 
    ( Tau * G_2t ( T_K, P_MPa ) - Pi * G_2p ( T_K, P_MPa ));
  return U;
  }

double CIF_97::S_2 ( double T_K, double P_MPa )
  {
  SetXY_2( T_K, P_MPa );
  double S = Rkg * ( Tau * G_2t ( T_K, P_MPa ) - G_2 ( T_K, P_MPa ));
  return S;
  }

double CIF_97::H_2 ( double T_K, double P_MPa )
	{
  SetXY_2( T_K, P_MPa );
	double Gamma = G_2t ( T_K, P_MPa );
	double H = Rkg * T_K * Tau * Gamma;
	return H;
	}

double CIF_97::Cp_2 ( double T_K, double P_MPa )
	{
  SetXY_2( T_K, P_MPa );
  double Cp = -Rkg * Tau * Tau * G_2tt ( T_K, P_MPa );
	return Cp;
	}

double CIF_97::Cv_2 ( double T_K, double P_MPa )
  {
  SetXY_2( T_K, P_MPa );
  double Gamma = G_2p( T_K, P_MPa ) - Tau * G_2pt( T_K, P_MPa );
  double Cv = Rkg * 
    ( -Tau * Tau * G_2tt ( T_K, P_MPa ) + 
      Gamma * Gamma / G_2pp ( T_K, P_MPa ));
	return Cv;
  }
